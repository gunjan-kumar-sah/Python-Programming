# Create string
x = "Hello Gunjan"
print(len(x))  # Output: 12

# Create list
x = ["apple", "banana", "cherry"]
print(len(x))  # Output: 3

# Create tuple
x = ("apple", "banana", "cherry")
print(len(x))  # Output: 3

# Create dictionary
x = {"apple": 5, "banana": 10, "cherry": 15}
print(len(x))  # Output: 3

# Create set
x = {"apple", "banana", "cherry"}
print(len(x))  # Output: 3

# Create frozenset
x = frozenset({"apple", "banana", "cherry"})
print(len(x))  # Output: 3

# Create bytes
x = b"Hello Gunjan"
print(len(x))  # Output: 12     

# Create Dictionary
gunjan = {
  "name": "Gunjan",
  "age": 21,
  "city": "Buxar"
}
print(len(gunjan))  # Output: 3
print(len(gunjan["name"]))  # Output: 6
print(len(gunjan["city"]))  # Output: 5
print(gunjan)